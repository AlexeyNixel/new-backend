/**
 * Достаёт число из хвоста старого id («gm120» -> 120, «gl-136» -> 136,
 * «393203» -> 393203) — грубый, неточный, но стабильный ключ сортировки:
 * старые id в источнике не хранят настоящую дату добавления, но их
 * порядковые номера хотя бы примерно соответствуют порядку добавления в
 * старый каталог. Используется только для того, чтобы у мигрированных игр
 * было хоть какое-то осмысленное значение createdAt для сортировки
 * «по дате добавления» — не для точной хронологии.
 */
export function extractExternalIdSortNumber(
  externalId: string | null | undefined,
): number {
  if (!externalId) {
    return 0;
  }

  const match = externalId.match(/(\d+)$/);
  return match ? Number(match[1]) : 0;
}
