/**
 * Эвристика для группировки игр в серии при миграции/пересчёте: часть
 * названия до первого разделителя-подзаголовка. Разделители — двоеточие
 * («Дюна: Приключения в Империи»), точка с пробелом («AZUL. Витражи
 * Синтры» — так оформлена часть каталога) или тире/дефис с пробелами по
 * бокам («Вся жизнь - игра»). Берётся первый встреченный разделитель, если
 * в названии их несколько («Unmatched: Битва Легенд. Том второй» → база —
 * «Unmatched», по двоеточию, а не по точке дальше).
 *
 * Точка требует пробела после себя, поэтому аббревиатуры без пробела
 * («V.I.P.», «т.д.») разделителем не считаются.
 *
 * Не находит серию (null), если разделителя нет или базовая часть слишком
 * короткая — такие случаи в основном шум (не признак серии).
 */
export function extractSeriesBaseTitle(title: string): string | null {
  const match = title.match(/^(.{2,}?)(?:\s*:\s+|\.\s+|\s+[—-]\s+)/);
  if (!match) {
    return null;
  }

  const base = match[1].trim();
  if (base.length < 2) {
    return null;
  }

  // Базовая часть с точкой внутри ("т.д", "V.I.P") — почти всегда хвост
  // аббревиатуры, а не название серии.
  if (base.includes('.')) {
    return null;
  }

  return base;
}
