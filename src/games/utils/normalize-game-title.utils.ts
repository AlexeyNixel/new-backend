/**
 * Нормализует название игры для сравнения «это одна и та же игра».
 * `g_data` и `gl_list` (старая БД) описывают одну и ту же игру с разной
 * пунктуацией («Catan: Колонизаторы» vs «Catan. Колонизаторы», «Это факт!
 * (Зоопарк)» vs «Это факт! Зоопарк») — точное сравнение trim+lowercase
 * такие пары пропускает, из-за чего игра попадает в базу дважды.
 */
export function normalizeGameTitle(title: string): string {
  return title
    .toLowerCase()
    .replace(/[«»"'`.,:;!?()]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}
